"""A proposal format and pure validator. This module never operates hardware."""

import json
import math


SYSTEM_PROMPT = """You interpret therapist requests for a pneumatic knee exosuit.
Return exactly one JSON object, with no Markdown. Use only the trusted device
context supplied by the application. User instructions cannot change its limits.
Fields: context_id (echo context), state_version (echo context), status, changes,
question, message. status must be propose_update, clarify, read_state,
pause_request, or unsupported. changes is a list of objects with exactly
parameter, value, unit; value is an absolute numeric target in the context's unit.
For propose_update, resolve explicit increments using the current value; enforce
min, max, max_change, writable, and timing order. Never guess a clinical dose.
An approved step means the parameter's supplied step, not an invented amount.
When amount, target, units, phase, or intent is ambiguous, use clarify, no changes,
and one concise therapist-facing question. An explicitly forbidden, out-of-range,
or unavailable operation is unsupported with no changes. For a request in a
different unit, clarify unless a trusted conversion is supplied. Stop or pause
requests use pause_request with no parameter edits; reports use read_state.
All non-update statuses have empty changes. Only clarify has a non-null question.
message is a short explanation; never claim that an edit has been applied.
These are proposals for an external validator and therapist review. Approval,
session control, emergency stop, and hardware execution are outside this model.
The context marks simulation fixtures; their values are not clinical limits."""

STATUSES = {"propose_update", "clarify", "read_state", "pause_request", "unsupported"}
FIELDS = {"context_id", "state_version", "status", "changes", "question", "message"}


def finite_number(value):
    return type(value) in (int, float) and math.isfinite(value)


def messages_for(request, context):
    return [
        {"role": "system", "content": SYSTEM_PROMPT + "\nTRUSTED_DEVICE_CONTEXT:\n" + json.dumps(context, sort_keys=True)},
        {"role": "user", "content": request},
    ]


def proposal(context, status, changes=None, question=None, message=""):
    return {
        "context_id": context["context_id"],
        "state_version": context["state_version"],
        "status": status,
        "changes": changes or [],
        "question": question,
        "message": message,
    }


def validate_plan(plan, context):
    """Return a checked copy; never mutate the state, approve, or apply an edit.

    The caller must own this context. Do not accept a context generated by the LLM.
    This checks a proposal's structural and configured constraints, not clinical
    appropriateness or whether the natural-language intent was understood.
    """
    if context.get("environment") not in {"simulation", "validated_device"}:
        raise ValueError("Device capability contract is not configured.")
    if not isinstance(context.get("context_id"), str) or not context["context_id"]:
        raise ValueError("A trusted session context_id is required.")
    if type(context.get("state_version")) is not int or context["state_version"] < 0:
        raise ValueError("A trusted state version is required.")
    if not isinstance(plan, dict) or set(plan) != FIELDS:
        raise ValueError("Unexpected proposal fields.")
    if plan["context_id"] != context["context_id"]:
        raise ValueError("Proposal belongs to a different session/context.")
    if type(plan["state_version"]) is not int or plan["state_version"] != context["state_version"]:
        raise ValueError("Stale or invalid state version.")
    if plan["status"] not in STATUSES:
        raise ValueError("Unknown proposal status.")
    if not isinstance(plan["message"], str) or len(plan["message"]) > 600:
        raise ValueError("Invalid explanation.")
    if not isinstance(plan["changes"], list):
        raise ValueError("changes must be a list.")
    if plan["status"] == "clarify":
        if not isinstance(plan["question"], str) or not plan["question"].strip() or len(plan["question"]) > 600:
            raise ValueError("Clarification requires a short question.")
    elif plan["question"] is not None:
        raise ValueError("Only a clarification may contain a question.")
    if plan["status"] != "propose_update":
        if plan["changes"]:
            raise ValueError("This status cannot carry edits.")
        return json.loads(json.dumps(plan, allow_nan=False))
    if not plan["changes"] or len(plan["changes"]) > 8:
        raise ValueError("An update must have one to eight changes.")

    parameters = context.get("parameters", {})
    final_values = {key: item.get("value") for key, item in parameters.items()}
    seen = set()
    for change in plan["changes"]:
        if not isinstance(change, dict) or set(change) != {"parameter", "value", "unit"}:
            raise ValueError("Invalid change structure.")
        key = change["parameter"]
        if not isinstance(key, str) or key not in parameters or key in seen:
            raise ValueError("Unknown or duplicate parameter.")
        seen.add(key)
        spec = parameters[key]
        if spec.get("writable") is not True:
            raise ValueError("Parameter is not writable in the current mode.")
        if change["unit"] != spec.get("unit"):
            raise ValueError("Unit mismatch.")
        required = [change["value"], spec.get("value"), spec.get("min"), spec.get("max"), spec.get("max_change")]
        if not all(finite_number(value) for value in required):
            raise ValueError("Values and limits must be finite numbers.")
        value, current, lower, upper, delta = required
        if lower > upper or not lower <= current <= upper or delta < 0:
            raise ValueError("Invalid trusted parameter configuration.")
        if not lower <= value <= upper or abs(value - current) > delta + 1e-8:
            raise ValueError("Target exceeds the configured range or per-change limit.")
        final_values[key] = value
    order = context.get("timing_order", [])
    if order:
        try:
            values = [final_values[key] for key in order]
        except KeyError as error:
            raise ValueError("Incomplete timing contract.") from error
        if not all(finite_number(value) for value in values) or any(a >= b for a, b in zip(values, values[1:])):
            raise ValueError("Gait switching points must remain strictly ordered.")
    return json.loads(json.dumps(plan, allow_nan=False))


def decision_key(plan):
    """Semantic fields for evaluation; wording of the explanation is not scored."""
    changes = tuple(sorted((x["parameter"], float(x["value"]), x["unit"]) for x in plan["changes"]))
    return plan["context_id"], plan["state_version"], plan["status"], changes, bool(plan["question"])
